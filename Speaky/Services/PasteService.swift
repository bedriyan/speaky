import AppKit
import Carbon.HIToolbox
import os

private let logger = Logger.speaky(category: "PasteService")

final class PasteService: @unchecked Sendable {
    typealias Snapshot = [[NSPasteboard.PasteboardType: Data]]

    private let pasteboard: NSPasteboard
    private let isTrusted: () -> Bool
    private let sendPasteKeystroke: @Sendable () -> Void
    private let readyDelay: TimeInterval
    private let restoreDelay: TimeInterval

    /// The user's clipboard from before the first of a run of dictations, and
    /// the change count our own write produced. Main thread only.
    private var pendingRestore: (items: Snapshot, changeCount: Int)?

    init(
        pasteboard: NSPasteboard = .general,
        isTrusted: @escaping () -> Bool = { AXIsProcessTrusted() },
        sendPasteKeystroke: (@Sendable () -> Void)? = nil,
        readyDelay: TimeInterval = Constants.Timing.pasteboardReadyDelay,
        restoreDelay: TimeInterval = Constants.Timing.pasteboardRestoreDelay
    ) {
        self.pasteboard = pasteboard
        self.isTrusted = isTrusted
        self.sendPasteKeystroke = sendPasteKeystroke ?? { PasteService.simulateCmdV() }
        self.readyDelay = readyDelay
        self.restoreDelay = restoreDelay
    }

    /// Paste text at the current cursor position using Cmd+V simulation.
    /// Returns `.pasted` on success, `.clipboardOnly` if accessibility is missing, `.skipped` for empty text.
    ///
    /// The user's clipboard is put back afterwards, but only if nothing else
    /// changed the clipboard in the meantime (the user copying something must
    /// win). Back-to-back dictations restore the clipboard from before the
    /// first one, not the previous dictation's text.
    @discardableResult
    func paste(_ text: String) -> PasteResult {
        guard !text.isEmpty else {
            logger.warning("Paste skipped — empty text")
            return .skipped
        }
        logger.info("Paste called — text length: \(text.count) characters")

        // If the previous dictation's restore hasn't run yet and the clipboard
        // still holds our text, the user's real clipboard is the one saved then.
        let original: Snapshot
        if let pending = pendingRestore, pending.changeCount == pasteboard.changeCount {
            original = pending.items
        } else {
            original = Self.snapshot(of: pasteboard)
        }

        pasteboard.clearContents()
        let item = NSPasteboardItem()
        item.setString(text, forType: .string)
        // Ask clipboard managers not to record dictations (nspasteboard.org).
        item.setData(Data(), forType: NSPasteboard.PasteboardType("org.nspasteboard.TransientType"))
        item.setData(Data(), forType: NSPasteboard.PasteboardType("org.nspasteboard.AutoGeneratedType"))
        pasteboard.writeObjects([item])
        let ourChangeCount = pasteboard.changeCount

        // Check accessibility - if not trusted, just leave text on clipboard
        guard isTrusted() else {
            pendingRestore = nil
            logger.warning("Accessibility not trusted — text copied to clipboard only. Please grant Accessibility in System Settings.")
            return .clipboardOnly
        }

        pendingRestore = (original, ourChangeCount)

        // Delay to ensure pasteboard is ready, then simulate Cmd+V on a background queue
        // to avoid blocking the main thread with usleep calls
        let sendKeystroke = sendPasteKeystroke
        let restoreDelay = restoreDelay
        DispatchQueue.global(qos: .userInteractive).asyncAfter(deadline: .now() + readyDelay) { [weak self] in
            sendKeystroke()
            DispatchQueue.main.asyncAfter(deadline: .now() + restoreDelay) { [weak self] in
                self?.restoreIfUnchanged(expectedChangeCount: ourChangeCount)
            }
        }
        return .pasted
    }

    private func restoreIfUnchanged(expectedChangeCount: Int) {
        // A newer dictation took over this restore.
        guard let pending = pendingRestore, pending.changeCount == expectedChangeCount else { return }
        pendingRestore = nil
        // Someone (usually the user) changed the clipboard since our write: keep theirs.
        guard pasteboard.changeCount == expectedChangeCount else {
            logger.info("Clipboard changed after paste — not restoring")
            return
        }
        Self.restore(pending.items, to: pasteboard)
    }

    /// Simulate Cmd+V keystroke using CGEvent
    private static func simulateCmdV() {
        let source = CGEventSource(stateID: .privateState)

        // Virtual key codes: 0x37 = Command, 0x09 = V
        guard let cmdDown = CGEvent(keyboardEventSource: source, virtualKey: 0x37, keyDown: true),
              let vDown = CGEvent(keyboardEventSource: source, virtualKey: 0x09, keyDown: true),
              let vUp = CGEvent(keyboardEventSource: source, virtualKey: 0x09, keyDown: false),
              let cmdUp = CGEvent(keyboardEventSource: source, virtualKey: 0x37, keyDown: false) else {
            logger.error("Failed to create CGEvents")
            return
        }

        cmdDown.flags = .maskCommand
        vDown.flags = .maskCommand
        vUp.flags = .maskCommand

        cmdDown.post(tap: .cghidEventTap)
        usleep(20_000)
        vDown.post(tap: .cghidEventTap)
        usleep(20_000)
        vUp.post(tap: .cghidEventTap)
        usleep(20_000)
        cmdUp.post(tap: .cghidEventTap)

        logger.notice("Cmd+V posted via CGEvent")
    }

    // MARK: - Clipboard save/restore

    static func snapshot(of pasteboard: NSPasteboard) -> Snapshot {
        pasteboard.pasteboardItems?.compactMap { item -> [NSPasteboard.PasteboardType: Data]? in
            var dict = [NSPasteboard.PasteboardType: Data]()
            for type in item.types {
                if let data = item.data(forType: type) {
                    dict[type] = data
                }
            }
            return dict.isEmpty ? nil : dict
        } ?? []
    }

    static func restore(_ items: Snapshot, to pasteboard: NSPasteboard) {
        // An empty original is restored too: the dictated text shouldn't
        // linger on a clipboard the user had left empty.
        pasteboard.clearContents()
        let restored = items.map { itemDict -> NSPasteboardItem in
            let item = NSPasteboardItem()
            for (type, data) in itemDict {
                item.setData(data, forType: type)
            }
            return item
        }
        if !restored.isEmpty {
            pasteboard.writeObjects(restored)
        }
    }

    // MARK: - Accessibility

    static func checkAccessibility() -> Bool {
        AXIsProcessTrusted()
    }

    static func requestAccessibility() {
        let promptKey = "AXTrustedCheckOptionPrompt" as CFString
        let options = [promptKey: true] as CFDictionary
        AXIsProcessTrustedWithOptions(options)
    }
}
